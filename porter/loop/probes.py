def collect_sections(ws: Path, order: list[str],
                      current_module: str, current_reg_path: Path,
                      kind: str = "P3") -> list[tuple[str, list[dict]]]:
    """聚合全部探针节：P2 预生成 + 各模块 P3/P4 + 当前调用方的节。

    当前模块用 current_reg_path（可能尚未落盘）。预生成自身调用时传
    current_module="(pregen)"，其注册表经 current_reg_path 进入。
    """
    sections: list[tuple[str, list[dict]]] = []
    if current_module != "(pregen)":
        reg = load_registry(ws.joinpath(*P2_REGISTRY_REL))
        if reg.get("probes"):
            sections.append(("P2(pregen)", reg["probes"]))
    for m in order:
        if m == current_module:
            continue
        for k in ("P3", "P4"):
            p = ws / k / m / "reports" / (
                "probes.json" if k == "P3" else "fill_probes.json")
            reg = load_registry(p)
            if reg.get("probes"):
                sections.append((f"{k}({m})", reg["probes"]))
    reg = load_registry(current_reg_path)
    if reg.get("probes"):
        current_marker = "P2(pregen)" if current_module == "(pregen)" \
            else f"{kind}({current_module})"
        sections.append((current_marker, reg["probes"]))
    return sections


def known_claims(ws: Path, order: list[str],
                 skip_module: str | None) -> set[str]:
    """已覆盖的 claim 集（含 downgraded——其主张已降级 gap 不会再进
    risky）。跨注册表去重用：同一主张不重复生成探针。
    skip_module=None 不跳过任何表（pregen 去重须含 P2 自身历史产出）。"""
    claims: set[str] = set()
    if skip_module != "(pregen)":
        for probe in load_registry(ws.joinpath(*P2_REGISTRY_REL)) \
                .get("probes", []):
            if probe.get("claim"):
                claims.add(probe["claim"])
    for m in order:
        if m == skip_module:
            continue
        for k in ("P3", "P4"):
            p = ws / k / m / "reports" / (
                "probes.json" if k == "P3" else "fill_probes.json")
            for probe in load_registry(p).get("probes", []):
                if probe.get("claim"):
                    claims.add(probe["claim"])
    return claims


def judge(log_text: str, names: list[str]) -> dict[str, str]:
    """判定每个探针：ok / fail / missing。"""
    out: dict[str, str] = {}
    for n in names:
        n_pass = log_text.count(f"PROBE_{n} PASS")
        n_fail = log_text.count(f"PROBE_{n} FAIL")
        if n_fail:
            out[n] = "fail"
        elif n_pass:
            out[n] = "ok"
        else:
            out[n] = "missing"
    return out


def call_probe_gen(prompt: str, target_os: Path,
                   log_stem: Path) -> tuple[dict | None, list[dict], list[str]]:
    """探针生成 agent 调用 + 校验。返回 (原始解析, 合格条目, 错误)。"""
    rc, out = agent.run_agent(prompt, workdir=target_os,
                              log_stem=str(log_stem),
                              timeout_sec=AGENT_TIMEOUT_SEC)
    if rc != 0:
        return None, [], [f"agent rc={rc}"]
    parsed = agent.extract_json(out)
    if not (isinstance(parsed, dict) and "probes" in parsed):
        return parsed, [], ["输出无 probes JSON 块"]
    ok, errs = validate_probes(parsed["probes"])
    return parsed, ok, errs


