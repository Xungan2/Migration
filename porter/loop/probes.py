"""probes.py — 高风险探针机器（plan §3.2；2026-08-30 起含 P2 末预生成）。

职责：
  - 筛选：使用面映射条目中 risk∈{med,high} ∪ confidence==low
  - 生成：agent 调用产出 20-50 行探针函数（只验证**映射主张本身**，
    打 `PROBE_<name> PASS/FAIL` 日志行），≤GEN_BATCH 条/批
  - 住骨架：src/probes.rs **整体再生成**（注册表驱动、确定性、幂等——
    手改会被下次同步覆盖，这是有意设计）
  - 判定：qemu.log 双信号（boot 退出码由 runner 把关，此处查特征行）
  - **共享生命周期** run_probe_lifecycle()：P3(M) 补新与 P2 末预生成
    （pregen）共用同一管线（生成 → 同步 → build → 编译回炉 → boot →
    判定 → FAIL 有界改判 → 降级 gap）。前置预生成的依据：探针贵且可
    长期复用（每次启动重跑=回归哨网），放在流程头部稳定阶段一次付清。

注册表位置（claim 跨注册表去重——同一主张只探测一次）：
  P2/reports/probes.json      预生成（节标记 P2(pregen)）
  P3/<M>/reports/probes.json  模块 P3 补新（节标记 P3(<M>)）
  P4/<M>/reports/fill_probes.json  平台补齐附带探针（节标记 P4(<M>)）
条目 {"name","code","claim","status"}（旧条目 rust 键兼容读）；
status=downgraded 的探针不再进
probes.rs（其主张已降级 gap）。
"""

