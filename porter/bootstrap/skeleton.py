"""skeleton.py — P2b 全局骨架生成器（目标 OS 专属模板：Asterinas 起步）。

骨架 = "在目标 OS 里新添驱动的入住仪式"（plan §3.1），**零驱动功能**：
  crate（no_std + deny(unsafe_code)）/ 空 probe（认设备 ID→日志→认领）/
  探针宿舍 / ktest 位 / 栈接线桩（new_<driver>() -> None）+ 全部接线点。

模板事实源：手工迁移提交 38925fd86（本机 asterinas 树 git 历史）+
migration/e1000/API_MAPPING.md「P3 接线清单」节 + PROGRESS.md 轮 7/8
（链接坑：host crate 无显式引用则 #[init_component] 静默不执行）。

接线点（幂等：marker 存在即跳过；写入清单落 P2/reports/）：
  1. kernel/core/comps/<driver>/{Cargo.toml, src/lib.rs, src/probes.rs}
  2. 根 Cargo.toml：members（×2 数组）+ [workspace.dependencies]
  3. Components.toml [components]
  4. kernel/core/Cargo.toml 依赖
  5. kernel/core/src/driver/mod.rs use 引用链接（轮 7 坑内置）
  6. kernel/core/src/net/iface/init.rs 栈接线桩（new_<driver>() -> None，
     行为不变：骨架不向 network core 注册任何设备）
"""

